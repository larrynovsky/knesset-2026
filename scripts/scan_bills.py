# Тот же дефект нашёлся снаружи проекта: в Wikidata поиск «רבנות» вернул
# памятники жертвам Холокоста, потому что «רבנות» ⊂ «קורבנות».
#
# СПРАВА граница строгая: ивритский суффикс меняет слово (המוסד → המוסדי).
# СЛЕВА допускается ОДНА служебная буква — в иврите предлоги и союзы пишутся
# слитно: «בבית המשפט» (в суде), «שהמוסד» (что Моссад). Строгая граница слева
# срезала бы их и уронила рекалл, а рекалл здесь важнее точности осознанно.
#
# Чего эта правка НЕ чинит, и это названо, а не спрятано: омонимы. «הרכב» —
# и «состав» (суда, комиссии), и «автомобиль». Оба стоят отдельными словами,
# границы их не различают. Нужен контекст, то есть сужение токена, — а это
# уже правка широты сети, которая выбрана сознательно и здесь не трогается.
HEB = "א-ת"
_PREFIX = "[הובלמשכ]?"      # ה ו ב ל מ ש כ


def _rx(tok: str) -> "re.Pattern":
    return re.compile(f"(?<![{HEB}]){_PREFIX}{re.escape(tok)}(?![{HEB}])")


LEX_RX = {g: [(w, _rx(w)) for w in ws] for g, ws in LEX.items()}
BASIC_LAW_RX = [_rx(w) for w in BASIC_LAW]
NOISE_RX = [_rx(w) for w in NOISE]


def hits(text: str) -> dict[str, list[str]]:
    t = text or ""
    out = {}
    for grp, pairs in LEX_RX.items():
        m = [w for w, rx in pairs if rx.search(t)]
        if m:
            out[grp] = m
    return out


def is_basic_law(text: str) -> bool:
    return any(rx.search(text or "") for rx in BASIC_LAW_RX)


def has_noise(text: str) -> bool:
    return any(rx.search(text or "") for rx in NOISE_RX)


